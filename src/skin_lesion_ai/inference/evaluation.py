def summarize_split_data(
    merged: pd.DataFrame,
) -> dict[str, int | float]:
    """Return basic lesion- and patient-level information."""
    total_lesions = len(merged)
    total_patients = merged["patient_id"].nunique()

    positive_lesions = int(merged["y_true"].sum())
    negative_lesions = total_lesions - positive_lesions

    patient_labels = merged.groupby("patient_id", sort=False)["y_true"].max()
    positive_patients = int(patient_labels.sum())

    return {
        "total_lesions": total_lesions,
        "total_patients": total_patients,
        "positive_lesions": positive_lesions,
        "negative_lesions": negative_lesions,
        "patients_with_positive_lesion": positive_patients,
        "lesion_prevalence": positive_lesions / total_lesions,
        "patient_prevalence": positive_patients / total_patients,
    }


