def _plot_precision_recall(
    train_merged: pd.DataFrame,
    validation_merged: pd.DataFrame,
    model_name: str,
    run_directory: Path,
) -> Path:
    """Save train and validation Precision-Recall curves."""
    set_eda_style()

    fig, ax = plt.subplots(figsize=EDA_STYLE["figure_size"])

    split_data = {
        "Train": (
            train_merged,
            STATISTIC_PALETTE["distribution"],
        ),
        "Validation": (
            validation_merged,
            STATISTIC_PALETTE["median"],
        ),
    }

    for split_name, (data, color) in split_data.items():
        y_true = data["y_true"].to_numpy(dtype=int)
        y_prob = data["y_prob"].to_numpy(dtype=float)

        precision, recall, _ = precision_recall_curve(
            y_true,
            y_prob,
        )
        pr_auc = auc(recall, precision)

        ax.plot(
            recall,
            precision,
            label=f"{split_name} (AUC = {pr_auc:.3f})",
            color=color,
            linewidth=2,
        )

    validation_prevalence = validation_merged["y_true"].mean()

    ax.axhline(
        validation_prevalence,
        linestyle="--",
        linewidth=1.5,
        color=STATISTIC_PALETTE["mean"],
        label=(f"Validation prevalence ({validation_prevalence:.3f})"),
    )

    ax.set_xlabel("Recall / Sensitivity")
    ax.set_ylabel("Precision / PPV")
    ax.set_title(f"Precision-Recall curve · {model_name}")
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1)
    ax.legend()

    output_path = _save_figure(
        fig,
        run_directory,
        "precision_recall_curve",
    )

    plt.close(fig)

    return output_path


