def _safe_divide(
    numerator: np.ndarray | float | int,
    denominator: np.ndarray | float | int,
) -> np.ndarray:
    """Divide safely and return NaN when the denominator is zero."""
    numerator_array = np.asarray(numerator, dtype=float)
    denominator_array = np.asarray(denominator, dtype=float)

    output_shape = np.broadcast_shapes(
        numerator_array.shape,
        denominator_array.shape,
    )

    result = np.full(
        output_shape,
        np.nan,
        dtype=float,
    )

    return np.divide(
        numerator_array,
        denominator_array,
        out=result,
        where=denominator_array != 0,
    )


def _confusion_counts_for_thresholds(
    y_true: np.ndarray,
    y_prob: np.ndarray,
    thresholds: np.ndarray,
) -> tuple[
    np.ndarray,
    np.ndarray,
    np.ndarray,
    np.ndarray,
]:
    """Efficiently compute confusion counts for multiple thresholds."""
    order = np.argsort(y_prob, kind="mergesort")
    sorted_probabilities = y_prob[order]
    sorted_labels = y_true[order]

    positive_prefix = np.concatenate(([0], np.cumsum(sorted_labels == 1)))
    negative_prefix = np.concatenate(([0], np.cumsum(sorted_labels == 0)))

    first_positive_index = np.searchsorted(
        sorted_probabilities,
        thresholds,
        side="left",
    )

    positives_below_threshold = positive_prefix[first_positive_index]
    negatives_below_threshold = negative_prefix[first_positive_index]

    total_positives = int((y_true == 1).sum())
    total_negatives = int((y_true == 0).sum())

    tp = total_positives - positives_below_threshold
    fp = total_negatives - negatives_below_threshold
    fn = positives_below_threshold
    tn = negatives_below_threshold

    return (
        tp.astype(int),
        tn.astype(int),
        fp.astype(int),
        fn.astype(int),
    )


def build_threshold_metrics_table(
    y_true: np.ndarray,
    y_prob: np.ndarray,
    thresholds: np.ndarray,
) -> pd.DataFrame:
    """Calculate clinical metrics for a collection of thresholds."""
    thresholds = np.asarray(thresholds, dtype=float)
    thresholds = np.unique(np.clip(thresholds, 0.0, 1.0))
    thresholds = np.sort(thresholds)[::-1]

    tp, tn, fp, fn = _confusion_counts_for_thresholds(
        y_true=y_true,
        y_prob=y_prob,
        thresholds=thresholds,
    )

    sensitivity = _safe_divide(tp, tp + fn)
    specificity = _safe_divide(tn, tn + fp)
    ppv = _safe_divide(tp, tp + fp)
    npv = _safe_divide(tn, tn + fn)

    fnr = _safe_divide(fn, tp + fn)
    fpr = _safe_divide(fp, tn + fp)

    f1_score = _safe_divide(
        2.0 * ppv * sensitivity,
        ppv + sensitivity,
    )

    f2_score = _safe_divide(
        5.0 * ppv * sensitivity,
        (4.0 * ppv) + sensitivity,
    )

    balanced_accuracy = (sensitivity + specificity) / 2.0

    total = tp + tn + fp + fn

    accuracy = _safe_divide(
        tp + tn,
        total,
    )

    # Convert to float before multiplying to avoid integer overflow
    # with large datasets.
    tp_float = tp.astype(float)
    tn_float = tn.astype(float)
    fp_float = fp.astype(float)
    fn_float = fn.astype(float)

    mcc_numerator = (tp_float * tn_float) - (fp_float * fn_float)

    mcc_denominator = np.sqrt(
        (tp_float + fp_float)
        * (tp_float + fn_float)
        * (tn_float + fp_float)
        * (tn_float + fn_float)
    )

    mcc = np.divide(
        mcc_numerator,
        mcc_denominator,
        out=np.zeros_like(
            mcc_numerator,
            dtype=float,
        ),
        where=mcc_denominator != 0,
    )

    predicted_positive_count = tp + fp

    return pd.DataFrame(
        {
            "threshold": thresholds,
            "tp": tp,
            "tn": tn,
            "fp": fp,
            "fn": fn,
            "sensitivity": sensitivity,
            "specificity": specificity,
            "fnr": fnr,
            "fpr": fpr,
            "ppv": ppv,
            "npv": npv,
            "f1_score": f1_score,
            "f2_score": f2_score,
            "balanced_accuracy": balanced_accuracy,
            "mcc": mcc,
            "accuracy": accuracy,
            "predicted_positive_count": (predicted_positive_count),
            "predicted_positive_rate": _safe_divide(
                predicted_positive_count,
                total,
            ),
            "tp_per_1000_lesions": (_safe_divide(tp, total) * 1000.0),
            "fp_per_1000_lesions": (_safe_divide(fp, total) * 1000.0),
            "fn_per_1000_lesions": (_safe_divide(fn, total) * 1000.0),
        }
    )


def select_clinical_threshold(
    y_true: np.ndarray,
    y_prob: np.ndarray,
    target_sensitivity: float,
) -> float:
    """Select the threshold maximizing specificity at target sensitivity."""
    if not 0.0 < target_sensitivity <= 1.0:
        raise ValueError("target_sensitivity must be in the interval (0, 1].")

    exact_thresholds = np.unique(y_prob)

    threshold_table = build_threshold_metrics_table(
        y_true=y_true,
        y_prob=y_prob,
        thresholds=exact_thresholds,
    )

    feasible_thresholds = threshold_table.loc[
        threshold_table["sensitivity"] >= target_sensitivity
    ].copy()

    if feasible_thresholds.empty:
        raise RuntimeError("No threshold reaches the requested target sensitivity.")

    # Tie-breaking order:
    # 1. Highest specificity.
    # 2. Highest sensitivity.
    # 3. Highest PPV.
    # 4. Highest F2.
    # 5. Highest threshold.
    feasible_thresholds = feasible_thresholds.sort_values(
        by=[
            "specificity",
            "sensitivity",
            "ppv",
            "f2_score",
            "threshold",
        ],
        ascending=[
            False,
            False,
            False,
            False,
            False,
        ],
        na_position="last",
    )

    return float(feasible_thresholds.iloc[0]["threshold"])


def compute_metrics_at_threshold(
    merged: pd.DataFrame,
    threshold: float,
) -> dict[str, float | int]:
    """Calculate metrics for one fixed threshold."""
    table = build_threshold_metrics_table(
        y_true=merged["y_true"].to_numpy(dtype=int),
        y_prob=merged["y_prob"].to_numpy(dtype=float),
        thresholds=np.array([threshold]),
    )

    row = table.iloc[0].to_dict()
    row.pop("threshold")

    return row


