def build_summary_table(
    train_summary: dict[str, int | float],
    validation_summary: dict[str, int | float],
    train_threshold_free: dict[str, float],
    validation_threshold_free: dict[str, float],
    train_threshold_metrics: dict[str, float | int],
    validation_threshold_metrics: dict[str, float | int],
    selected_threshold: float,
) -> pd.DataFrame:
    """Build one train-versus-validation metrics table."""
    train_results = {
        **train_summary,
        **train_threshold_free,
        "selected_threshold": selected_threshold,
        **train_threshold_metrics,
    }

    validation_results = {
        **validation_summary,
        **validation_threshold_free,
        "selected_threshold": selected_threshold,
        **validation_threshold_metrics,
    }

    metric_order = [
        "total_lesions",
        "total_patients",
        "positive_lesions",
        "negative_lesions",
        "patients_with_positive_lesion",
        "lesion_prevalence",
        "patient_prevalence",
        "pr_auc",
        "roc_auc",
        "brier_score",
        "selected_threshold",
        "tp",
        "tn",
        "fp",
        "fn",
        "sensitivity",
        "specificity",
        "fnr",
        "fpr",
        "ppv",
        "npv",
        "f1_score",
        "f2_score",
        "balanced_accuracy",
        "mcc",
        "accuracy",
        "predicted_positive_count",
        "predicted_positive_rate",
        "tp_per_1000_lesions",
        "fp_per_1000_lesions",
        "fn_per_1000_lesions",
    ]

    return pd.DataFrame(
        {
            "metric": metric_order,
            "train": [train_results[metric] for metric in metric_order],
            "validation": [validation_results[metric] for metric in metric_order],
        }
    )


