def _plot_precision_recall(
    train_merged: pd.DataFrame,
    validation_merged: pd.DataFrame,
    run_directory: Path,
) -> Path:
    """Save train and validation Precision-Recall curves."""
    set_eda_style()

    fig, ax = plt.subplots(figsize=EDA_STYLE["figure_size"])

    split_data = {
        "Entrenamiento": (
            train_merged,
            STATISTIC_PALETTE["distribution"],
        ),
        "Validación": (
            validation_merged,
            STATISTIC_PALETTE["median"],
        ),
    }

    for split_name, (data, color) in split_data.items():
        y_true = data["y_true"].to_numpy(dtype=int)
        y_prob = data["y_prob"].to_numpy(dtype=float)

