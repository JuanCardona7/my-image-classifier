def _resolve_project_path(path_value: str | Path) -> Path:
    """Resolve a path relative to the project root."""
    path_value = Path(path_value)

    if path_value.is_absolute():
        return path_value

    return get_project_root() / path_value


def _get_models_directory(
    config_path: str | Path = DEFAULT_CONFIG_PATH,
) -> Path:
    """Read the models directory from the YAML configuration."""
    resolved_config_path = _resolve_project_path(config_path)
    config = load_yaml_config(resolved_config_path)

    try:
        configured_models_path = config["paths"]["models"]
    except KeyError as exc:
        raise KeyError("The configuration file must contain 'paths.models'.") from exc

    models_directory = _resolve_project_path(configured_models_path)
    models_directory.mkdir(parents=True, exist_ok=True)

    return models_directory


def _sanitize_model_name(model_name: str) -> str:
    """Convert a model name into a filesystem-safe directory name."""
    if not isinstance(model_name, str) or not model_name.strip():
        raise ValueError("model_name must be a non-empty string.")

    safe_name = re.sub(
        r"[^A-Za-z0-9._-]+",
        "_",
        model_name.strip(),
    )
    safe_name = safe_name.strip("._-")

    if not safe_name:
        raise ValueError("model_name must contain at least one valid character.")

    return safe_name


def _create_run_directory(
    model_name: str,
    config_path: str | Path = DEFAULT_CONFIG_PATH,
) -> Path:
    """Create a model run directory inside the configured models folder."""
    models_directory = _get_models_directory(config_path)
    safe_name = _sanitize_model_name(model_name)

    run_directory = models_directory / safe_name

    if not run_directory.exists():
        run_directory.mkdir()
        return run_directory

    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    run_directory = models_directory / f"{safe_name}_{timestamp}"

    counter = 1

    while run_directory.exists():
        run_directory = models_directory / (f"{safe_name}_{timestamp}_{counter:02d}")
        counter += 1

    run_directory.mkdir()

    return run_directory


