def _validate_hypothesis(hypothesis: int) -> None:
    """Validate the selected clinical hypothesis."""
    if hypothesis not in (1, 2):
        raise ValueError("hypothesis must be either 1 or 2.")


def _resolve_label_column(
    hypothesis: int,
    label_col: str | None,
) -> str:
    """Return the target column corresponding to the hypothesis."""
    _validate_hypothesis(hypothesis)

    if label_col is not None:
        return label_col

    return DEFAULT_LABEL_COLUMNS[hypothesis]


def _validate_and_merge_split(
    df_predictions: pd.DataFrame,
    df_split: pd.DataFrame,
    label_col: str,
    prediction_id_col: str,
    probability_col: str,
    split_id_col: str,
    patient_id_col: str,
    split_name: str,
) -> pd.DataFrame:
    """Validate and merge predictions with one train or validation split."""
    required_prediction_columns = {
        prediction_id_col,
        probability_col,
    }
    required_split_columns = {
        split_id_col,
        patient_id_col,
        label_col,
    }

    missing_prediction_columns = required_prediction_columns - set(
        df_predictions.columns
    )
    missing_split_columns = required_split_columns - set(df_split.columns)

    if missing_prediction_columns:
        raise KeyError(
            f"{split_name} predictions are missing columns: "
            f"{sorted(missing_prediction_columns)}"
        )

    if missing_split_columns:
        raise KeyError(
            f"{split_name} data are missing columns: {sorted(missing_split_columns)}"
        )

    predictions = df_predictions[[prediction_id_col, probability_col]].copy()

    split = df_split[[split_id_col, patient_id_col, label_col]].copy()

    if predictions[prediction_id_col].isna().any():
        raise ValueError(
            f"{split_name} predictions contain missing lesion identifiers."
        )

    if split[split_id_col].isna().any():
        raise ValueError(f"{split_name} data contain missing lesion identifiers.")

    if split[patient_id_col].isna().any():
        raise ValueError(f"{split_name} data contain missing patient identifiers.")

    if predictions[prediction_id_col].duplicated().any():
        raise ValueError(
            f"{split_name} predictions contain duplicated lesion identifiers."
        )

    if split[split_id_col].duplicated().any():
        raise ValueError(f"{split_name} data contain duplicated lesion identifiers.")

    predictions[probability_col] = pd.to_numeric(
        predictions[probability_col],
        errors="raise",
    )

    split[label_col] = pd.to_numeric(
        split[label_col],
        errors="raise",
    )

    if predictions[probability_col].isna().any():
        raise ValueError(
            f"{split_name} predicted probabilities contain missing values."
        )

    if not np.isfinite(predictions[probability_col]).all():
        raise ValueError(
            f"{split_name} predicted probabilities contain infinite values."
        )

    if not predictions[probability_col].between(0.0, 1.0).all():
        raise ValueError(
            f"{split_name} predicted probabilities must be between 0 and 1."
        )

    if split[label_col].isna().any():
        raise ValueError(f"{split_name} target column contains missing values.")

    observed_labels = set(split[label_col].unique())

    if not observed_labels.issubset({0, 1}):
        raise ValueError(f"{split_name} target column must contain only 0 and 1.")

    if observed_labels != {0, 1}:
        raise ValueError(
            f"{split_name} must contain at least one positive and one negative lesion."
        )

    predictions[prediction_id_col] = predictions[prediction_id_col].astype(str)
    split[split_id_col] = split[split_id_col].astype(str)

    prediction_ids = set(predictions[prediction_id_col])
    split_ids = set(split[split_id_col])

    missing_predictions = split_ids - prediction_ids
    unknown_predictions = prediction_ids - split_ids

    if missing_predictions or unknown_predictions:
        raise ValueError(
            f"Lesion identifiers do not match for {split_name}. "
            f"Lesions without prediction: {len(missing_predictions)}. "
            f"Predictions without matching lesion: "
            f"{len(unknown_predictions)}."
        )

    predictions = predictions.rename(
        columns={
            prediction_id_col: "lesion_id",
            probability_col: "y_prob",
        }
    )

    split = split.rename(
        columns={
            split_id_col: "lesion_id",
            patient_id_col: "patient_id",
            label_col: "y_true",
        }
    )

    merged = split.merge(
        predictions,
        on="lesion_id",
        how="inner",
        validate="one_to_one",
    )

    merged["y_true"] = merged["y_true"].astype(int)
    merged["y_prob"] = merged["y_prob"].astype(float)

    return merged


