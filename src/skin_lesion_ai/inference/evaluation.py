def evaluate(
    df_train_predictions: pd.DataFrame,
    df_validation_predictions: pd.DataFrame,
    df_train: pd.DataFrame,
    df_validation: pd.DataFrame,
    hypothesis: int,
    model_name: str,
    target_sensitivity: float = 0.95,
    *,
    config_path: str | Path = DEFAULT_CONFIG_PATH,
    prediction_id_col: str = "isic_id",
    probability_col: str = "probability",
    split_id_col: str = "isic_id",
    patient_id_col: str = "patient_id",
    label_col: str | None = None,
) -> dict:
    """Evaluate one model on train and validation data.

    The clinical threshold is selected exclusively from the validation set.
    The selected threshold is subsequently applied unchanged to train and
    validation.

    Parameters
    ----------
    df_train_predictions:
        Train predictions with lesion identifier and positive-class
        probability.

    df_validation_predictions:
        Validation predictions with lesion identifier and positive-class
        probability.

    df_train:
        Original train split containing lesion ID, patient ID and target.

    df_validation:
        Original validation split containing lesion ID, patient ID and target.

    hypothesis:
        1 = lesion recommended for biopsy.
        2 = lesion suspected to be malignant.

    model_name:
        Name used for the model-specific output directory.

    target_sensitivity:
        Minimum validation sensitivity required during threshold selection.

    config_path:
        YAML configuration path, relative to the project root unless absolute.

    prediction_id_col:
        Lesion identifier column in prediction dataframes.

    probability_col:
        Positive-class probability column in prediction dataframes.

    split_id_col:
        Lesion identifier column in train and validation split dataframes.

    patient_id_col:
        Patient identifier column in train and validation dataframes.

    label_col:
        Optional explicit target column. If omitted, target_biopsy or
        target_malignant is selected according to hypothesis.

    Returns
    -------
    dict
        Dictionary containing the summary table, threshold table, selected
        threshold, output directory and generated output paths.
    """
    _validate_hypothesis(hypothesis)

    resolved_label_col = _resolve_label_column(
        hypothesis=hypothesis,
        label_col=label_col,
    )

    train_merged = _validate_and_merge_split(
        df_predictions=df_train_predictions,
        df_split=df_train,
        label_col=resolved_label_col,
        prediction_id_col=prediction_id_col,
        probability_col=probability_col,
        split_id_col=split_id_col,
        patient_id_col=patient_id_col,
        split_name="train",
    )

    validation_merged = _validate_and_merge_split(
        df_predictions=df_validation_predictions,
        df_split=df_validation,
        label_col=resolved_label_col,
        prediction_id_col=prediction_id_col,
        probability_col=probability_col,
        split_id_col=split_id_col,
        patient_id_col=patient_id_col,
        split_name="validation",
    )

    train_y_true = train_merged["y_true"].to_numpy(dtype=int)

    train_y_prob = train_merged["y_prob"].to_numpy(dtype=float)

    validation_y_true = validation_merged["y_true"].to_numpy(dtype=int)

    validation_y_prob = validation_merged["y_prob"].to_numpy(dtype=float)

    train_summary = summarize_split_data(train_merged)

    validation_summary = summarize_split_data(validation_merged)

    train_threshold_free = compute_threshold_free_metrics(
        y_true=train_y_true,
        y_prob=train_y_prob,
    )

    validation_threshold_free = compute_threshold_free_metrics(
        y_true=validation_y_true,
        y_prob=validation_y_prob,
    )

    selected_threshold = select_clinical_threshold(
        y_true=validation_y_true,
        y_prob=validation_y_prob,
        target_sensitivity=target_sensitivity,
    )

    train_threshold_metrics = compute_metrics_at_threshold(
        merged=train_merged,
        threshold=selected_threshold,
    )

    validation_threshold_metrics = compute_metrics_at_threshold(
        merged=validation_merged,
        threshold=selected_threshold,
    )

    summary_table = build_summary_table(
        train_summary=train_summary,
        validation_summary=validation_summary,
        train_threshold_free=train_threshold_free,
        validation_threshold_free=validation_threshold_free,
        train_threshold_metrics=train_threshold_metrics,
        validation_threshold_metrics=(validation_threshold_metrics),
        selected_threshold=selected_threshold,
    )

    saved_thresholds = np.unique(
        np.append(
            THRESHOLD_GRID,
            selected_threshold,
        )
    )

    validation_threshold_table = build_threshold_metrics_table(
        y_true=validation_y_true,
        y_prob=validation_y_prob,
        thresholds=saved_thresholds,
    )

    validation_threshold_table["meets_target_sensitivity"] = (
        validation_threshold_table["sensitivity"] >= target_sensitivity
    )

    validation_threshold_table["is_selected_threshold"] = np.isclose(
        validation_threshold_table["threshold"],
        selected_threshold,
        rtol=0.0,
        atol=1e-12,
    )

    run_directory = _create_run_directory(
        model_name=model_name,
        config_path=config_path,
    )

    csv_paths = save_validation_outputs(
        summary_table=summary_table,
        threshold_table=validation_threshold_table,
        run_directory=run_directory,
    )

    figure_paths = save_evaluation_figures(
        train_merged=train_merged,
        validation_merged=validation_merged,
        validation_metrics=validation_threshold_metrics,
        selected_threshold=selected_threshold,
        target_sensitivity=target_sensitivity,
        hypothesis=hypothesis,
        model_name=model_name,
        run_directory=run_directory,
    )

    print_validation_summary(
        model_name=model_name,
        hypothesis=hypothesis,
        train_summary=train_summary,
        validation_summary=validation_summary,
        train_threshold_free=train_threshold_free,
        validation_threshold_free=validation_threshold_free,
        train_metrics=train_threshold_metrics,
        validation_metrics=validation_threshold_metrics,
        selected_threshold=selected_threshold,
        target_sensitivity=target_sensitivity,
        run_directory=run_directory,
    )

    return {
        "summary": summary_table,
        "threshold_metrics": validation_threshold_table,
        "selected_threshold": selected_threshold,
        "output_directory": run_directory,
        "csv_paths": csv_paths,
        "figure_paths": figure_paths,
    }
